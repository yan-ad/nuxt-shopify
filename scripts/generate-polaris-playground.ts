import ts from 'typescript'
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'

const metadata: Record<string, unknown> = {}
for (const file of readdirSync('src/runtime/components/polaris').filter(
  (file) => file.endsWith('.vue')
)) {
  const source = readFileSync(`src/runtime/components/polaris/${file}`, 'utf8')
  const script = source.match(/<script[^>]*>([\s\S]*?)<\/script>/)?.[1] || ''
  const ast = ts.createSourceFile(
    file + '.ts',
    script,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS
  )
  const controls: unknown[] = []
  function visit(node: ts.Node) {
    if (
      ts.isCallExpression(node) &&
      node.expression.getText(ast) === 'defineProps'
    ) {
      const type = node.typeArguments?.[0]
      if (type && ts.isTypeLiteralNode(type))
        for (const member of type.members) {
          if (!ts.isPropertySignature(member) || !member.type || !member.name)
            continue
          const name = member.name.getText(ast)
          if (['id', 'slot', 'commandFor', 'interestFor'].includes(name))
            continue
          const text = member.type.getText(ast)
          const options = [...text.matchAll(/'([^']*)'/g)]
            .map((match) => match[1])
            .filter((value) => value !== '')
          controls.push({
            name,
            kind:
              text === 'boolean'
                ? 'boolean'
                : text === 'number'
                  ? 'number'
                  : options.length
                    ? 'select'
                    : 'text',
            ...(options.length ? { options: [...new Set(options)] } : {})
          })
        }
    }
    ts.forEachChild(node, visit)
  }
  visit(ast)
  metadata[
    file
      .replace('.vue', '')
      .replace(
        /[A-Z]/g,
        (letter, offset) => (offset ? '-' : '') + letter.toLowerCase()
      )
  ] = controls
}
writeFileSync(
  'docs/app/utils/polaris-props.ts',
  '// Generated by bun run docs:props. Do not edit manually.\nexport const polarisProps = ' +
    JSON.stringify(metadata, null, 2) +
    ' as const\n'
)
